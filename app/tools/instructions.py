def build_tools_use(enabled_tools: Optional[Iterable[str]] = None) -> List[Dict[str, Any]]:
    """Возвращает tools в формате OpenAI API с опциональной фильтрацией по именам."""
    if enabled_tools is None:
        names = list(TOOLS.keys())
    else:
        names = [name for name in enabled_tools if name in TOOLS]

    return [
        {"type": "function", "function": {"name": name, **TOOLS[name]}}
        for name in names
    ]


