"""
Пример использования новой логики обработки инструментов в Airi.
Демонстрирует:
1. Молчание если ИИ не вызвала озвучку
2. Озвучивание результата text_to_audio функции
3. Отправку результатов других функций обратно в ИИ
"""

# ============ СЦЕНАРИЙ 1: ИИ НЕ ВЫЗВАЛА ФУНКЦИИ ============
# Пользователь: "Привет"
# ИИ: "Привет! Как дела?"
# Результат: 🤐 МОЛЧИТ, в историю сохранен ответ

SCENARIO_1 = {
    "user_input": "Привет",
    "ai_response": {
        "content": "Привет! Как дела?",
        "tool_calls": []  # ПУСТО!
    },
    "action": "⏸️ Молчит и ждет следующей команды"
}


# ============ СЦЕНАРИЙ 2: ИИ ВЫЗВАЛА text_to_audio ============
# Пользователь: "Расскажи мне что-нибудь интересное"
# ИИ: [Решает озвучить ответ сам]
# ИИ вызывает: text_to_audio("Вот интересный факт: ...")
# Результат: 🔊 Озвучивает результат функции

SCENARIO_2 = {
    "user_input": "Расскажи мне что-нибудь интересное",
    "ai_response": {
        "content": "Вот интересный факт...",
        "tool_calls": [
            {
                "id": "call_1",
                "function": {
                    "name": "text_to_audio",
                    "arguments": '{"text": "Вот интересный факт: земля вращается..."}'
                }
            }
        ]
    },
    "action": "🔊 Озвучивает результат text_to_audio"
}


# ============ СЦЕНАРИЙ 3: ИИ ВЫЗВАЛА ДРУГУЮ ФУНКЦИЮ ============
# Пользователь: "Какая погода в Москве?"
# ИИ вызывает: get_weather({"location": "Москва"})
# Функция возвращает: {"temperature": 20, "condition": "Облачно"}
# ИИ отправляется НОВЫЙ запрос с результатом
# ИИ отвечает: "В Москве 20 градусов и облачно"
# ИИ может вызвать text_to_audio для озвучки
# Результат: ⚙️ Выполнение функции → 📤 Запрос к ИИ → 🔊 Озвучка если вызовет

SCENARIO_3 = {
    "user_input": "Какая погода в Москве?",
    "ai_response_1": {
        "content": "Сейчас я проверю погоду...",
        "tool_calls": [
            {
                "id": "call_1",
                "function": {
                    "name": "get_weather",
                    "arguments": '{"location": "Москва"}'
                }
            }
        ]
    },
    "function_result": {
        "status": "success",
        "result": {"temperature": 20, "condition": "Облачно", "humidity": 65}
    },
    "ai_response_2": {
        "content": "В Москве сейчас 20 градусов и облачно",
        "tool_calls": [
            {
                "id": "call_2",
                "function": {
                    "name": "text_to_audio",
                    "arguments": '{"text": "В Москве сейчас двадцать градусов и облачно"}'
                }
            }
        ]
    },
    "action": "⚙️ Выполнить get_weather → 📤 Отправить результат в ИИ → 🔊 Озвучить text_to_audio"
}


# ============ СЦЕНАРИЙ 4: СМЕШАННЫЕ ФУНКЦИИ ============
# ИИ вызывает несколько функций сразу
# text_to_audio - озвучить результат
# get_weather - выполнить, отправить результат обратно в ИИ
# Результат: 🔊 Озвучить + ⚙️ Выполнить + 📤 Запрос в ИИ

SCENARIO_4 = {
    "user_input": "Включи музыку и скажи погоду",
    "ai_response": {
        "content": "Включаю музыку и проверяю погоду...",
        "tool_calls": [
            {
                "id": "call_1",
                "function": {
                    "name": "text_to_audio",
                    "arguments": '{"text": "Озвучиваю погоду"}'
                }
            },
            {
                "id": "call_2",
                "function": {
                    "name": "get_weather",
                    "arguments": '{"location": "Москва"}'
                }
            }
        ]
    },
    "action": "🔊 Озвучить + ⚙️ Выполнить get_weather в параллели → 📤 Результат в ИИ"
}


# ============ ЛОГИКА ОБРАБОТКИ В thread_process_ai ============
"""
1. Получить ответ от ИИ
2. Проверить наличие tool_calls
   
   ❌ Если нет tool_calls:
      → Сохранить в историю
      → ⏸️ МОЛЧАТЬ И ЖДАТЬ
   
   ✅ Если есть tool_calls:
      → Разделить на две группы:
         a) text_to_audio - выполнить, добавить в очередь озвучки
         b) Остальные - выполнить, отправить результаты в ИИ
      
      → Если были остальные функции:
         → Отправить результаты обратно в ИИ
         → Получить новый ответ от ИИ
         → Проверить новый ответ на text_to_audio
         → Если есть → озвучить
      
      → Если только text_to_audio:
         → Озвучить результаты
      
      → Сохранить всё в историю
"""


if __name__ == "__main__":
    print("Примеры сценариев новой логики обработки инструментов")
    print("=" * 60)
    
    for i, scenario in enumerate([SCENARIO_1, SCENARIO_2, SCENARIO_3, SCENARIO_4], 1):
        print(f"\n📝 Сценарий {i}: {scenario.get('action')}")
        print(f"   Пользователь: {scenario.get('user_input')}")
        print(f"   Результат: {scenario.get('action')}")
